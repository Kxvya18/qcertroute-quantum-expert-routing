"""Reliability-Aware Graph Mixture of Experts for BA3.

RAG-MoE has a temporal MLP, a fixed interpretable Boltzmann expert, and a
node-level gate.  Gate labels are generated by a two-way cross-fitted temporal
expert on training episodes only.  The external LANL fold is never used to fit
the selector or the feature scaler.
"""
from __future__ import annotations

import argparse
import gzip
import json
import pickle
