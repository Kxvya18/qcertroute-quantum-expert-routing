from pathlib import Path

import numpy as np
import pandas as pd
import torch
from torch import nn
from torch.nn import functional as F

from .episodes import rolling_folds
from .evaluate import _CompatibleUnpickler
from .metrics import ranking, softmax
from .prior import fit_endpoint_choice_prior, reliability
from .prior import fisher_identity
from .synthetic import grow


CONDITIONS = ("complete", "random50", "hub50", "auth_only", "dns_only")
SEEDS = (7, 19, 42, 73, 101)


@dataclass
class EpisodeData:
    identifier: int
    x: np.ndarray              # pre-activity plus four query summaries
    structural: np.ndarray     # centred, unweighted log Boltzmann probability
    degree: np.ndarray
    truth: int
    rho: float
    se: float
    gini: float
    source_history: float = 0.0
    source_novelty: float = 0.0
    # Optional condition-specific structural evidence.  The default preserves
    # the original RAG-MoE data contract for controlled and legacy datasets.
    structural_by_condition: dict[str, np.ndarray] = field(default_factory=dict)
    graph_history_retention: dict[str, float] = field(default_factory=dict)


def load_records(path):
    with gzip.open(path, "rb") as handle:
        return _CompatibleUnpickler(handle).load()


def _counts(counter, nodes):
    return np.log1p(np.asarray([counter.get(node, 0.0) for node in nodes], dtype=np.float32))


def _gini(values):
    values = np.sort(np.asarray(values, dtype=float))
    if not values.size or values.sum() <= 0:
        return 0.0
    index = np.arange(1, values.size + 1)
    return float((2.0 * (index * values).sum() / (values.size * values.sum())) - (values.size + 1.0) / values.size)


def build_episode(record, cap, scale):
    pool = record.pre_activity + record.calibration_degree + record.fit_choices
    nodes = [node for node, _ in pool.most_common(cap) if node.startswith("C")]
    if record.episode.origin not in nodes:
        return None
    degree = np.asarray([record.calibration_degree.get(node, 0.0) for node in nodes], dtype=float)
    choices = np.asarray([record.fit_choices.get(node, 0.0) for node in nodes], dtype=float)
    beta, information, probability = fit_endpoint_choice_prior(degree, choices)
    rho = reliability(information, scale)
    residual = np.log(np.clip(probability, 1e-12, 1.0))
    residual = residual - residual.mean()
    query = np.column_stack((
        _counts(record.post_activity["auth"], nodes),
        _counts(record.post_contact["auth"], nodes),
        _counts(record.post_activity["dns"], nodes),
        _counts(record.post_contact["dns"], nodes),
    ))
    x = np.column_stack((_counts(record.pre_activity, nodes), query)).astype(np.float32)
    return EpisodeData(record.episode.identifier, x, residual.astype(np.float32), degree.astype(np.float32),
                       nodes.index(record.episode.origin), rho, 1.0 / np.sqrt(max(information, 1e-9)), _gini(degree))


def mask_for(data, condition, rng):
    n = len(data.degree)
    mask = np.ones((n, 4), dtype=np.float32)
    if condition == "random50":
        mask = (rng.random((n, 4)) >= 0.5).astype(np.float32)
    elif condition == "hub50":
        # Structured observability loss removes every modality from the most connected half.
        mask[np.argsort(data.degree)[n // 2 :], :] = 0.0
    elif condition == "auth_only":
        mask[:, 2:] = 0.0
    elif condition == "dns_only":
        mask[:, :2] = 0.0
    return mask


class RAGMoE(nn.Module):
    def __init__(self, width=24):
        super().__init__()
        self.temporal = nn.Sequential(nn.Linear(9, width), nn.GELU(), nn.Dropout(0.10), nn.Linear(width, width // 2), nn.GELU(), nn.Linear(width // 2, 1))
        self.gate = nn.Sequential(nn.Linear(6, 16), nn.GELU(), nn.Linear(16, 1))

    def forward(self, x, structural, global_features):
        temporal = self.temporal(x).squeeze(-1)
        posterior = torch.softmax(temporal, dim=0)
        entropy = -(posterior * torch.log(posterior + 1e-8)).sum()
        entropy /= max(float(np.log(max(len(temporal), 2))), 1e-8)
        # Rank disagreement is scale-free and prevents arbitrary logit scales
        # from becoming a shortcut for the gate.
        temporal_rank = torch.argsort(torch.argsort(temporal.detach())).float()
        structural_rank = torch.argsort(torch.argsort(structural.detach())).float()
        disagreement = torch.abs(temporal_rank - structural_rank) / max(len(temporal) - 1, 1)
        gate_x = torch.column_stack((
            global_features[:, 0], entropy.expand_as(temporal), disagreement,
            global_features[:, 1], global_features[:, 2], global_features[:, 3],
        ))
        alpha = torch.sigmoid(self.gate(gate_x).squeeze(-1))
        fused = temporal + alpha * global_features[:, 0] * structural
        return temporal, alpha, fused


def build_input(data, mask):
    # Four observed values plus four explicit availability bits retain the missingness mechanism.
    values = data.x[:, 1:] * mask
    return np.column_stack((data.x[:, 0], values, mask)).astype(np.float32)


def scaler_fit(train):
    rows = []
    for item in train:
        rows.append(build_input(item, np.ones((len(item.degree), 4), dtype=np.float32)))
    x = np.vstack(rows)
    return x.mean(axis=0), x.std(axis=0).clip(1e-5)


def tensors(data, mask, mean, std, indices=None):
    x = (build_input(data, mask) - mean) / std
    if indices is not None:
        x = x[indices]
        structural = data.structural[indices]
        degree = data.degree[indices]
    else:
        structural, degree = data.structural, data.degree
    missing = 1.0 - float(mask.mean())
    global_features = np.column_stack((
        np.full(len(x), data.rho),
        np.full(len(x), missing),
        np.full(len(x), np.log1p(data.se)),
        np.full(len(x), data.gini),
    )).astype(np.float32)
    return (torch.tensor(x), torch.tensor(structural, dtype=torch.float32), torch.tensor(global_features), degree)


def sample_indices(data, rng, count=1200):
    others = np.delete(np.arange(len(data.degree)), data.truth)
    negatives = rng.choice(others, min(count, len(others)), replace=False)
    return np.concatenate(([data.truth], negatives))


def train_temporal(train, mean, std, seed, epochs=12, device="cpu", batch_size=32):
    torch.manual_seed(seed)
    device = torch.device(device)
    model = RAGMoE().to(device)
    optimizer = torch.optim.AdamW(model.temporal.parameters(), lr=3e-3, weight_decay=1e-4)
    rng = np.random.default_rng(seed)
    model.train()
    ordered = list(train)
    for _ in range(epochs):
        rng.shuffle(ordered)
        for start in range(0, len(ordered), batch_size):
            batch = ordered[start:start + batch_size]
            rows = []
            lengths = []
            for data in batch:
                index = sample_indices(data, rng)
                condition = CONDITIONS[int(rng.integers(len(CONDITIONS)))]
                mask = mask_for(data, condition, rng)
                x, _, _, _ = tensors(data, mask, mean, std, index)
                rows.append(x)
                lengths.append(len(x))
            joined = torch.cat(rows, dim=0).to(device)
            logits = model.temporal(joined).squeeze(-1)
            losses = []
            offset = 0
            for length in lengths:
                segment = logits[offset:offset + length]
                losses.append(F.cross_entropy(
                    segment.unsqueeze(0), torch.zeros(1, dtype=torch.long, device=device)
                ))
                offset += length
            loss = torch.stack(losses).mean()
            optimizer.zero_grad(); loss.backward(); optimizer.step()
    return model.to("cpu")


def gate_targets(train, mean, std, seed):
    """Cross-fitted soft targets estimate how much structural evidence is useful."""
    labels = {}
    admission_grid = np.asarray((0.0, 0.05, 0.10, 0.20, 0.35, 0.50, 0.75, 1.0))
    ordered = list(train)
    halves = (ordered[::2], ordered[1::2])
    for target, source in ((halves[0], halves[1]), (halves[1], halves[0])):
        if not source:
            source = target
        model = train_temporal(source, mean, std, seed + len(labels) + 101, epochs=25)
        model.eval()
        for data in target:
            for offset, condition in enumerate(CONDITIONS):
                mask = mask_for(data, condition, np.random.default_rng(seed + data.identifier + 1009 * offset))
                x, structural, global_features, _ = tensors(data, mask, mean, std)
                with torch.no_grad():
                    temporal = model.temporal(x).squeeze(-1).numpy()
                utilities = np.asarray([
                    ranking(softmax(temporal + alpha * data.rho * data.structural), data.truth)["mrr"]
                    for alpha in admission_grid
                ])
                # np.argmax returns the smallest admission on a tie, making the
                # target conservative when topology does not alter the rank.
                labels[(data.identifier, condition)] = float(admission_grid[int(np.argmax(utilities))])
    return labels


def train_rag(train, mean, std, seed, epochs=40):
    torch.manual_seed(seed)
    model = RAGMoE()
    pretrained = train_temporal(train, mean, std, seed, epochs=40)
    model.temporal.load_state_dict(pretrained.temporal.state_dict())
    for parameter in model.temporal.parameters():
        parameter.requires_grad = False
    targets = gate_targets(train, mean, std, seed)
    optimizer = torch.optim.AdamW(model.gate.parameters(), lr=2e-3, weight_decay=1e-4)
    rng = np.random.default_rng(seed)
    model.train()
    for _ in range(epochs):
        for data in train:
            index = sample_indices(data, rng)
            condition = CONDITIONS[int(rng.integers(len(CONDITIONS)))]
            mask = mask_for(data, condition, rng)
            x, structural, global_features, _ = tensors(data, mask, mean, std, index)
            gate_y = torch.full((len(index),), targets.get((data.identifier, condition), 0.0))
            temporal, alpha, fused = model(x, structural, global_features)
            truth = torch.zeros(1, dtype=torch.long)
            rank_loss = F.cross_entropy(fused.unsqueeze(0), truth)
            y = torch.zeros(len(index)); y[0] = 1.0
            brier = torch.mean((torch.softmax(fused, dim=0) - y) ** 2)
            gate_loss = F.binary_cross_entropy(alpha, gate_y)
            loss = rank_loss + 0.25 * brier + 0.75 * gate_loss + 0.04 * alpha.mean()
            optimizer.zero_grad(); loss.backward(); optimizer.step()
    return model


def predict(model, data, condition, mean, std, seed):
    model.eval(); mask = mask_for(data, condition, np.random.default_rng(seed + data.identifier))
    x, structural, global_features, _ = tensors(data, mask, mean, std)
    with torch.no_grad():
        temporal, alpha, fused = model(x, structural, global_features)
    return temporal.numpy(), alpha.numpy(), fused.numpy(), float(mask.mean())


def evaluate_lanl(records, output, cap=20000):
    episodes = [record.episode for record in records]
    rows = []
    for fold, train_ep, test_ep in rolling_folds(episodes):
        raw = [build_episode(record, cap, 1.0) for record in records if record.episode.identifier in {e.identifier for e in train_ep}]
        raw = [x for x in raw if x is not None]
        scale = float(np.median([1 / max(x.se * x.se, 1e-12) for x in raw])) if raw else 1.0
        by_id = {record.episode.identifier: build_episode(record, cap, scale) for record in records}
        train = [by_id[e.identifier] for e in train_ep if by_id[e.identifier] is not None]
        test = [by_id[e.identifier] for e in test_ep if by_id[e.identifier] is not None]
        if len(train) < 3 or not test:
            continue
        mean, std = scaler_fit(train)
        for seed in SEEDS:
            model = train_rag(train, mean, std, seed)
            for data in test:
                for condition in CONDITIONS:
                    temporal, alpha, fused, observed = predict(model, data, condition, mean, std, seed)
                    for name, score in (
                        ("temporal_mlp", temporal),
                        ("structural", data.rho * data.structural),
                        ("unconditional", temporal + data.structural),
                        ("fixed_curvature", temporal + data.rho * data.structural),
                        ("rag_moe", fused),
                    ):
                        row = {"fold": fold, "seed": seed, "episode": data.identifier, "condition": condition, "model": name, "observed_fraction": observed, "gate_mean": float(alpha.mean()), "gate_truth": float(alpha[data.truth]), "rho": data.rho, "se": data.se, "gini": data.gini}
                        row.update(ranking(softmax(score), data.truth)); rows.append(row)
    frame = pd.DataFrame(rows)
    output.mkdir(parents=True, exist_ok=True)
    frame.to_csv(output / "rag_lanl_results.csv", index=False)
    frame.groupby(["condition", "model"]).agg(instances=("episode", "size"),mrr=("mrr","mean"),hit5=("hit5","mean"),hit10=("hit10","mean"),nll=("nll","mean"),gate=("gate_mean","mean"),observed=("observed_fraction","mean")).reset_index().to_csv(output / "rag_lanl_summary.csv", index=False)
    return frame


def synthetic_population(beta, m, start, count, n=300):
    """Known-mechanism observations used only to test selective fusion regimes."""
    raw = []
    for offset in range(count):
        rng = np.random.default_rng(1_000_000 + int(beta * 100_000) + m * 10_000 + start + offset)
        degree, _ = grow(n, m, beta, rng)
        probability = softmax(beta * np.log1p(degree))
        truth = int(rng.choice(n, p=probability))
        # Pre-event activity is intentionally weak; post-event modalities carry a sparse noisy signal.
        pre = np.log1p(rng.poisson(0.35, n)).astype(np.float32)
        pre[truth] += np.log1p(rng.poisson(2.0))
        query = np.column_stack((
            np.log1p(rng.poisson(0.08, n)), np.log1p(rng.poisson(0.04, n)),
            np.log1p(rng.poisson(0.07, n)), np.log1p(rng.poisson(0.03, n)),
        )).astype(np.float32)
        query[truth] += np.log1p(rng.poisson(np.asarray([9.0, 4.0, 7.0, 3.0]))).astype(np.float32)
        information = float(n * fisher_identity(degree, beta))
        raw.append((start + offset, pre, query, degree.astype(np.float32), truth, information))
    scale = float(np.median([item[-1] for item in raw]))
    result = []
    for identifier, pre, query, degree, truth, information in raw:
        rho = reliability(information, scale)
        p = softmax(beta * np.log1p(degree))
        structural = np.log(np.clip(p, 1e-12, 1.0)) - np.log(np.clip(p, 1e-12, 1.0)).mean()
        result.append(EpisodeData(identifier, np.column_stack((pre, query)), structural.astype(np.float32), degree, truth, rho,
                                  1.0 / np.sqrt(max(information, 1e-9)), _gini(degree)))
    return result


def evaluate_synthetic(output):
    rows = []
    identifier = 0
    for beta in (0.0, 1.0, 2.0):
        for m in (1, 2, 3):
            population = synthetic_population(beta, m, identifier, 36)
            identifier += 36
            train, test = population[:24], population[24:]
            mean, std = scaler_fit(train)
            for seed in SEEDS:
                model = train_rag(train, mean, std, seed)
                for data in test:
                    for condition in CONDITIONS:
                        temporal, alpha, fused, observed = predict(model, data, condition, mean, std, seed)
                        for name, score in (
                            ("temporal_mlp", temporal),
                            ("structural", data.rho * data.structural),
                            ("unconditional", temporal + data.structural),
                            ("fixed_curvature", temporal + data.rho * data.structural),
                            ("rag_moe", fused),
                        ):
                            row = {"beta": beta, "m": m, "seed": seed, "episode": data.identifier, "condition": condition,
                                   "model": name, "observed_fraction": observed, "gate_mean": float(alpha.mean()), "gate_truth": float(alpha[data.truth]),
                                   "rho": data.rho, "se": data.se, "gini": data.gini}
                            row.update(ranking(softmax(score), data.truth)); rows.append(row)
    frame = pd.DataFrame(rows)
    frame.to_csv(output / "rag_synthetic_results.csv", index=False)
    frame.groupby(["beta", "m", "condition", "model"]).agg(instances=("episode", "size"),mrr=("mrr","mean"),hit1=("hit1","mean"),hit5=("hit5","mean"),nll=("nll","mean"),gate=("gate_mean","mean"),observed=("observed_fraction","mean")).reset_index().to_csv(output / "rag_synthetic_summary.csv", index=False)
    return frame


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--candidate-cap", type=int, default=20000)
    parser.add_argument("--skip-synthetic", action="store_true")
    args = parser.parse_args()
    lanl = evaluate_lanl(load_records(args.input), args.output, args.candidate_cap)
    synthetic = pd.DataFrame() if args.skip_synthetic else evaluate_synthetic(args.output)
    print(json.dumps({"lanl_rows": len(lanl), "synthetic_rows": len(synthetic), "output": str(args.output)}, indent=2))


if __name__ == "__main__":
    main()
